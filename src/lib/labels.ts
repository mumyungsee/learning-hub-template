// ─────────────────────────────────────────────────────────────
// ★ 화면에 뜨는 이름표를 정하는 단 한 곳.
//
// 왜 여기 모았나 — 전엔 같은 표가 네 파일에 복사돼 있었다(사이드바·위키 상세·
// 서재·개별 책). 위키에 종류를 하나 추가할 때 네 곳을 다 고쳐야 했고,
// 한 곳만 빠뜨리면 그 화면에서만 이름표가 빈칸으로 떴다.
//
// 그래서 규칙은 하나다:
//   ★ 화면에 뜨는 이름표는 여기서만 정하고, 다른 파일은 여기서 가져다 쓴다.
//   새 종류를 만들 땐 ①src/content/config.ts 의 종류 목록 ②이 파일 ③정렬 순서
//   (src/lib/content.ts 의 `종류순서`) — 이 셋만 보면 된다.
// ─────────────────────────────────────────────────────────────

// 위키 글의 종류 이름표.
// 짧은 쪽 = 좁은 자리(좌측 목록·목록 배지) / 긴 쪽 = 글 맨 위 큰 배지.
export const 종류이름 = {
  로드맵: { 짧게: '지도', 길게: '전체 지도' },
  계획: { 짧게: '계획', 길게: '이번 주 계획' },
  개념: { 짧게: '개념', 길게: '개념' },
  사례: { 짧게: '사례', 길게: '사례' },
  회고: { 짧게: '회고', 길게: '주차 회고' },
} as const;

// 모르는 종류가 와도 화면이 안 깨지게 — 이름표가 없으면 값을 그대로 보여준다.
export function 종류라벨(종류: string | undefined, 길이: '짧게' | '길게' = '짧게'): string {
  if (!종류) return '';
  const found = (종류이름 as Record<string, { 짧게: string; 길게: string }>)[종류];
  return found ? found[길이] : 종류;
}

// 프로젝트 상태 이름표. 값 자체가 이미 한글이라 그대로 쓰지만,
// 나중에 상태를 늘리거나 이름을 바꿀 때 여기만 고치면 되도록 한 곳에 둔다.
export const 상태이름: Record<string, string> = {
  진행중: '진행중',
  완성: '완성',
};

export function 상태라벨(status: string | undefined): string {
  if (!status) return '';
  return 상태이름[status] ?? status;
}
